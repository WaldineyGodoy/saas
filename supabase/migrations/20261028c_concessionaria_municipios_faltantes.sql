-- Depois da correção de códigos (20261028b), 330 municípios do IBGE seguiam
-- sem linha, quase todos homônimos de cidades de outros estados (Santa
-- Luzia/PB, Floresta/PR, São José do Rio Preto/SP...). A distribuidora de cada
-- um é a com mais UCs ativas no município pelo INDGER da ANEEL (dados
-- comerciais, ref. 09/2026). Os valores de tarifa e impostos vêm da linha
-- mais comum dessa distribuidora na própria tabela; distribuidora sem
-- nenhuma linha na tabela (ex.: Roraima Energia) fica de fora, pois não há
-- tarifa de referência para copiar.

